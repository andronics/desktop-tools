REAL = ("cat", "pgrep")
# The PATH pytest started with: only for finding a real tool a test checks against (zsh -n).
SYSTEM_PATH = os.environ.get("PATH", "")


def lockdown_path(base: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    import shutil

    bin_dir, real_dir = base / "bin", base / "real"
    bin_dir.mkdir(exist_ok=True)
    real_dir.mkdir(exist_ok=True)
    for name in REAL:
        found = shutil.which(name, path=SYSTEM_PATH)
        if found:
            (real_dir / name).symlink_to(found)
    trip = base / "tripwires.log"
    for name in DESKTOP:
        script = bin_dir / name
        script.write_text(
            f"#!{sys.executable}\nimport sys, json\n"
            f"open({str(trip)!r}, 'a').write(json.dumps([{name!r}, *sys.argv[1:]]) + '\\n')\n"
            "sys.exit(97)\n",
            encoding="utf-8",
        )
        script.chmod(0o755)
    monkeypatch.setenv("PATH", f"{bin_dir}{os.pathsep}{real_dir}")


def tripwires(base: Path) -> list[list[str]]:
    """The desktop commands a test reached without faking them."""
    trip = base / "tripwires.log"
    return calls(trip) if trip.exists() else []


def fake_commands(base: Path, monkeypatch: pytest.MonkeyPatch, bodies: dict[str, str]) -> Path:
    """Write each body as a script on a bin folder first on PATH. Each first logs its name and
    arguments to calls.log. A body is Python, with `args` (sys.argv[1:]) and `here` (base)."""
    bin_dir = base / "bin"
    bin_dir.mkdir(exist_ok=True)
    log = base / "calls.log"
    log.touch()
    for name, body in bodies.items():
        script = bin_dir / name
        script.write_text(
            f"#!{sys.executable}\n"
            "import sys, os, json, time\n"
            "args = sys.argv[1:]\n"
            f"here = {str(base)!r}\n"
            f"with open({str(log)!r}, 'a') as fh:\n"
            f"    fh.write(json.dumps([{name!r}, *args]) + '\\n')\n" + body + "\n",
            encoding="utf-8",
        )
        script.chmod(0o755)
    return log


def calls(log: Path) -> list[list[str]]:
    import json

    return [json.loads(line) for line in log.read_text().splitlines() if line.strip()]


def run(argv: list[str], **kw: Any) -> subprocess.CompletedProcess[str]:
    """A tool or a fake as a real process, as polybar, systemd or a shell would run it."""
    kw.setdefault("capture_output", True)
    kw.setdefault("text", True)
    kw.setdefault("check", False)
    # S603/S607: the tests' own fixed command lines, by design.
    return subprocess.run(argv, **kw)  # noqa: S603


def start(argv: list[str], **kw: Any) -> subprocess.Popen[str]:
    kw.setdefault("text", True)
    return subprocess.Popen(argv, **kw)  # noqa: S603 - the tests' own fixed command line
