"""zsh completions for each tool, generated from its Typer command tree (dotfiles record 0003 §A6).

One `_<tool>_cmd` file per tool, in the dotfiles' style (📐 Tooling Conventions): `#compdef`,
the generated marker, subcommands with their help, each subcommand's options and arguments. Live
values (module names, menus) come from the tool at TAB time with TOOL_STATS=skip, cached for the
shell's life, and nothing is offered, quietly, when the tool is missing or fails.

`scripts/gen-completions.py` writes them into `completions/zsh/` (and `--check` fails when they
are stale); `desktop-tools completions zsh --out <dir>` writes the installed version's.
"""

from __future__ import annotations

import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

import typer

MARKER = "Generated by scripts/gen-completions.py from the Typer app: don't edit it."


def _q(text: str) -> str:
    """Single-quoted for zsh."""
    return "'" + text.replace("'", "'\\''") + "'"


def _desc(text: str) -> str:
    """One line of help, safe inside _arguments' [...] and _describe's name:desc."""
    first = " ".join((text or "").split())
    for stop in (". ", ": "):
        if stop in first:
            first = first.split(stop, 1)[0]
    first = first.rstrip(".")
    return first.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]").replace(":", "\\:")


class Tool:
    """A tool to complete: its Typer app, a line about it, and how its live values are listed."""

    def __init__(
        self,
        name: str,
        app: typer.Typer,
        about: str,
        lists: dict[str, tuple[str, str]],
        params: dict[str, str] | None = None,
        live_commands: tuple[str, str] | None = None,
    ) -> None:
        # lists: argument name -> (tag, the command whose output lists its values)
        # params: argument name -> a zsh action used as is (e.g. _normal)
        # live_commands: (tag, command) listing subcommands made from config (barmenu's menus)
        self.name, self.app, self.about = name, app, about
        self.lists, self.params = lists, params or {}
        self.live_commands = live_commands

    def fn(self, tag: str) -> str:
        return f"_{self.name}_cmd_{tag}"


def _helper(tool: Tool, tag: str, command: str) -> list[str]:
    cache = f"_{tool.name}_cmd_cache_{tag}"
    return [
        f"{tool.fn(tag)}() {{",
        "    local -a expl",
        f"    if (( ! ${{#{cache}}} )); then",
        f"        (( ${{+commands[{tool.name}]}} )) || return 1",
        f"        typeset -ga {cache}",
        f'        {cache}=(${{(f)"$(TOOL_STATS=skip {command} 2>/dev/null </dev/null)"}})',
        f"        (( ${{#{cache}}} )) || return 1",
        "    fi",
        f'    _wanted {tag} expl {tag.rstrip("s")} compadd "$@" -a {cache}',
        "}",
        "",
    ]


def _spec(tool: Tool, param: Any) -> str:
    kind = getattr(param, "param_type_name", "")
    help_ = _desc(getattr(param, "help", "") or "")
    choices = getattr(param.type, "choices", None)
    if kind == "option":
        names = [*param.opts, *param.secondary_opts]
        if param.is_flag:
            spec = f"[{help_}]"
            values = ""
        else:
            action = f"({' '.join(str(c) for c in choices)})" if choices else " "
            spec = f"=[{help_}]"
            values = f":{param.name}:{action}"
        exclusive = f"({' '.join(names)})" if len(names) > 1 else ""
        if len(names) > 1:
            return f"{_q(exclusive)}{{{','.join(names)}}}{_q(spec + values)}"
        return _q(f"{names[0]}{spec}{values}")
    name = param.name
    if name in tool.params:
        action = tool.params[name]
    elif name in tool.lists:
        action = tool.fn(tool.lists[name][0])
    elif choices:
        action = f"({' '.join(str(c) for c in choices)})"
    else:
        action = " "
    variadic = param.nargs == -1
    prefix = "*:" if variadic else ":"
    if variadic and action == "_normal":
        prefix = "*::"
    label = name.rstrip("s") if variadic else name
    optional = "" if param.required or variadic else ":"
    return _q(f"{prefix}{optional}{label}:{action}") if not optional else _q(f"::{label}:{action}")


def zsh(tool: Tool) -> str:
    root: Any = typer.main.get_command(tool.app)
    commands = dict(sorted(getattr(root, "commands", {}).items()))
    lines = [
        f"#compdef {tool.name}",
        "",
        f"# Completion for `{tool.name}` (andronics/desktop-tools): {tool.about}",
        "#",
        f"# {MARKER}",
        "# Change the app and run `uv run scripts/gen-completions.py`; an installed desktop-tools",
        "# writes the same file with `desktop-tools completions zsh --out <dir>`. Named",
        f"# _{tool.name}_cmd, after the dotfiles' completions (see _coord_cmd).",
    ]
    if tool.lists or tool.live_commands:
        lines += [
            "#",
            "# Live values come from the tool at TAB time (TOOL_STATS=skip: no run record), cached",
            "# for the shell's life; nothing is offered, quietly, when it is missing or fails.",
        ]
    lines.append("")
    done: set[str] = set()
    for tag, command in [
        *tool.lists.values(),
        *([tool.live_commands] if tool.live_commands else []),
    ]:
        if tag not in done:
            done.add(tag)
            lines += _helper(tool, tag, command)
    lines += [
        f"_{tool.name}_cmd() {{",
        "    local curcontext=$curcontext state state_descr line",
        "    typeset -A opt_args",
        "    local -a commands",
        "    commands=(",
    ]
    for name, cmd in commands.items():
        lines.append(
            f"        {_q(name.replace(':', chr(92) + ':') + ':' + _desc(cmd.help or ''))}"
        )
    lines += [
        "    )",
        "",
        "    _arguments -C \\",
        "        '(- *)'{-h,--help}'[Show help and exit]' \\",
        "        '1:command:->command' \\",
        "        '*::arg:->args'",
        "",
        "    case $state in",
        "        command)",
        f"            _describe -t commands {_q(tool.name + ' command')} commands",
        *([f"            {tool.fn(tool.live_commands[0])}"] if tool.live_commands else []),
        "            ;;",
        "        args)",
        f"            curcontext=${{curcontext%:*:*}}:{tool.name}-$words[1]:",
        "            case $words[1] in",
    ]
    for name, cmd in commands.items():
        specs = ["'(- *)'{-h,--help}'[Show help and exit]'"]
        params = [p for p in cmd.params if getattr(p, "name", "") != "help"]
        specs += [_spec(tool, p) for p in params if p.param_type_name == "option"]
        specs += [_spec(tool, p) for p in params if p.param_type_name == "argument"]
        lines.append(f"                {name})")
        lines.append("                    _arguments -s -S \\")
        for i, spec in enumerate(specs):
            end = " \\" if i < len(specs) - 1 else ""
            lines.append(f"                        {spec}{end}")
        lines.append("                    ;;")
    lines += [
        "            esac",
        "            ;;",
        "    esac",
        "}",
        "",
        f'_{tool.name}_cmd "$@"',
        "",
    ]
    return "\n".join(lines)


def tools() -> list[Tool]:
    from desktop_tools.barctl.app import app as barctl
    from desktop_tools.barmenu.cli import build
    from desktop_tools.crew.app import app as crew

    return [
        Tool(
            "barctl",
            barctl,
            "the Polybar controller (dotfiles record 0003).",
            {"module": ("modules", "barctl list"), "modules": ("modules", "barctl list")},
        ),
        Tool(
            "barmenu",
            build({}),
            "the polybar menu buttons as rofi menus.",
            {},
            {"command": "_normal"},
            ("menus", "barmenu list"),
        ),
        Tool(
            "crew",
            crew,
            "the coordinator switchboard (brain record 0019).",
            {"name": ("names", "crew names"), "names_": ("names", "crew names")},
        ),
    ]


def _stdout(line: str) -> None:
    sys.stdout.write(line + "\n")


def write(out: Path, check: bool = False, emit: Callable[[str], None] = _stdout) -> int:
    """Write (or, with check, compare) one file per tool; 1 when a file is stale."""
    stale = []
    if not check:
        out.mkdir(parents=True, exist_ok=True)
    for tool in tools():
        path = out / f"_{tool.name}_cmd"
        text = zsh(tool)
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            stale.append(path)
            if not check:
                path.write_text(text, encoding="utf-8")
    if check and stale:
        for path in stale:
            emit(f"error: {path} is stale: run `uv run scripts/gen-completions.py`")
        return 1
    emit(("stale: " if check else "updated: ") + (", ".join(map(str, stale)) or "none"))
    return 0
