ROLES = {"unavailable": "#111111", "idle": "#222222", "active": "#333333", "alert": "#444444"}
HEADER = struct.Struct("<7sBIB")


def write_theme(state: Path) -> dict[str, str]:
    current = state / "current"
    current.mkdir(parents=True, exist_ok=True)
    current.joinpath("theme.zsh").write_text(
        "# Generated by `theme`.\n"
        "typeset -gA THEME_ROLE=(\n"
        f"    [dim]='{ROLES['unavailable']}'\n"
        f"    [fg_dim]='{ROLES['idle']}'\n"
        f"    [accent]='{ROLES['active']}'\n"
        f"    [urgent]='{ROLES['alert']}'\n"
        ")\n"
        "typeset -gA THEME_PALETTE=(\n    [base0D]='#7fbbb3'\n)\n",
        encoding="utf-8",
    )
    return dict(ROLES)


class FakeBar:
    """A polybar IPC socket: records every message, answers OK (or as told)."""

    def __init__(self, folder: Path, pid: int = 4242, version: int = 0, ok: bool = True) -> None:
        folder.mkdir(parents=True, exist_ok=True)
        self.path = folder / f"ipc.{pid}.sock"
        self.pid, self.version, self.ok = pid, version, ok
        self.messages: list[tuple[int, str]] = []
        self.silent = False
        self.sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        self.sock.bind(str(self.path))
        self.sock.listen(16)
        self.sock.settimeout(0.1)
        self.stopping = False
        self.thread = threading.Thread(target=self._serve, daemon=True)
        self.thread.start()

    def _serve(self) -> None:
        while not self.stopping:
            try:
                conn, _ = self.sock.accept()
            except TimeoutError:
                continue
            except OSError:
                return
            with conn:
                conn.settimeout(1)
                try:
                    head = conn.recv(HEADER.size)
                    _magic, _version, size, kind = HEADER.unpack(head)
                    body = conn.recv(size).decode() if size else ""
                except (OSError, struct.error):
                    continue
                self.messages.append((kind, body))
                if self.silent:
                    time.sleep(0.5)
                    continue
                answer = b"" if self.ok else b"bad"
                conn.sendall(
                    HEADER.pack(b"polyipc", self.version, len(answer), 0 if self.ok else 255)
                    + answer
                )

    def actions(self) -> list[str]:
        return [body for kind, body in self.messages if kind == 1 and "barctl-ping" not in body]

    def pokes(self) -> list[str]:
        return [a.split(".hook")[0].lstrip("#") for a in self.actions()]

    def wait(self, count: int, timeout: float = 3.0) -> list[str]:
        """The pokes, once there are at least count, plus a moment for a stray extra one."""
        end = time.monotonic() + timeout
        while len(self.pokes()) < count and time.monotonic() < end:
            time.sleep(0.02)
        time.sleep(0.3)
        return self.pokes()

    def clear(self) -> None:
        self.messages.clear()

    def close(self) -> None:
        self.stopping = True
        self.sock.close()
        self.thread.join(1)


class FakeJournal:
    """The journal's native datagram socket."""

    def __init__(self, path: Path) -> None:
        self.path = path
        self.sock = socket.socket(socket.AF_UNIX, socket.SOCK_DGRAM)
        self.sock.bind(str(path))
        self.sock.setblocking(False)

    def received(self, wait: float = 0.2) -> list[dict[str, str]]:
        out, end = [], time.time() + wait
        while time.time() < end:
            try:
                out.append(decode(self.sock.recv(1 << 20)))
            except BlockingIOError:
                time.sleep(0.02)
        return out

    def close(self) -> None:
        self.sock.close()


def decode(data: bytes) -> dict[str, str]:
    """The journal's native format, both value forms."""
    fields, i = {}, 0
    while i < len(data):
        nl = data.index(b"\n", i)
        line = data[i:nl]
        if b"=" in line:
            k, v = line.split(b"=", 1)
            fields[k.decode()] = v.decode()
            i = nl + 1
        else:
            size = struct.unpack("<Q", data[nl + 1 : nl + 9])[0]
            fields[line.decode()] = data[nl + 9 : nl + 9 + size].decode()
            i = nl + 9 + size + 1
    return fields


