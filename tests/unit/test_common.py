def test_xdg_paths_follow_the_environment(isolate: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    assert paths.config_home() == isolate / "xdg" / "config"
    assert paths.runtime_dir() == isolate / "xdg" / "runtime"
    monkeypatch.setenv("XDG_STATE_HOME", "relative/path")  # invalid by the spec: ignored
    assert paths.state_home() == Path.home() / ".local/state"
    monkeypatch.delenv("XDG_RUNTIME_DIR")
    assert paths.runtime_dir() == Path(f"/run/user/{os.getuid()}")
    monkeypatch.delenv("XDG_DATA_HOME")
    assert paths.data_home() == Path.home() / ".local/share"


def test_theme_roles_from_theme_zsh(theme: dict[str, str]) -> None:
    wanted = {"unavailable": "dim", "idle": "fg_dim", "active": "accent", "alert": "urgent"}
    assert th.roles(wanted) == theme == ROLES


def test_theme_lookup_order_and_missing(isolate: Path) -> None:
    path = isolate / "t.zsh"
    path.write_text(
        textwrap.dedent(
            """\
            typeset -gA THEME_ROLE=(
                [accent]='#a7c080'
            )
            typeset -gA THEME_PALETTE=(
                [accent]='#000000'
                [base0D]="#7fbbb3"
            )
            typeset -gA THEME_METRIC=(
                [gap]=5
            )
            """
        )
    )
    got = th.roles({"a": "accent", "b": "base0D", "g": "gap", "x": "nosuch"}, path)
    assert got == {"a": "#a7c080", "b": "#7fbbb3", "g": "5"}
    # No theme at all: no roles, and no colour written in this repo to fall back on.
    assert th.roles({"a": "accent"}, isolate / "missing.zsh") == {}
    assert th.theme_file() == isolate / "xdg" / "state" / "theme" / "current" / "theme.zsh"


def test_the_live_theme_format_parses() -> None:
    """Real data: the generated theme.zsh's shape (taken from a build on 2026-11-04)."""
    text = (
        "# Generated by `theme` from everforest. Do not edit.\n"
        "typeset -gA THEME_META=(\n    [id]='20261103T230126-3b7c'\n    [degraded]=false\n)\n"
        "typeset -gA THEME_ROLE=(\n    [accent]='#a7c080'\n    [dim]='#859289'\n"
        "    [fg_dim]='#9da9a0'\n    [urgent]='#e67e80'\n)\n"
        "typeset -ga THEME_ANSI=(\n    '#2d353b'\n)\n"
    )
    tables = th.parse(text)
    assert tables["THEME_ROLE"]["urgent"] == "#e67e80"
    assert tables["THEME_META"]["degraded"] == "false"
    assert "THEME_ANSI" not in tables


def test_query(commands: Callable[..., Path]) -> None:
    commands(ok="print('out')", bad="sys.exit(3)", slow="time.sleep(5)")
    assert procs.query(["ok"]) == "out\n"
    assert procs.query(["bad"]) is None
    assert procs.query(["slow"], timeout=0.2) is None
    assert procs.query(["no-such-command-here"]) is None


def test_stream_reads_lines_and_stops(commands: Callable[..., Path]) -> None:
    commands(follow="print('a', flush=True)\nprint('b', flush=True)\ntime.sleep(30)")
    stream = procs.Stream(["follow"])
    lines = stream.lines()
    assert next(lines) == "a"
    assert next(lines) == "b"
    stream.stop()
    assert stream.proc.poll() is not None


def test_detach_starts_a_new_session(commands: Callable[..., Path], isolate: Path) -> None:
    log = commands(
        child=f"open({str(isolate / 'sid')!r}, 'w').write(str(os.getsid(0) == os.getpid()))"
    )
    pid = procs.detach(["child"], env={**os.environ, "X": "1"}, cwd=isolate)
    os.waitpid(pid, 0)
    assert calls(log) == [["child"]]
    assert (isolate / "sid").read_text() == "True"


def test_close_inherited_drops_pipes_only(tmp_path: Path) -> None:
    """In a child, as a click handler would be: an inherited pipe beyond 0-2 goes, stdout that
    is a pipe goes to /dev/null, a file stays."""
    code = textwrap.dedent(
        """\
        import os, sys
        from desktop_tools.common import procs
        r, w = os.pipe()
        f = os.open(sys.argv[1], os.O_WRONLY | os.O_CREAT)
        changed = procs.close_inherited()
        assert r in changed and w in changed, changed
        assert f not in changed
        assert 1 in changed
        os.write(f, b"done")
        """
    )
    result = fakes.run(
        [sys.executable, "-c", code, str(tmp_path / "f")],
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    assert (tmp_path / "f").read_text() == "done"
    assert result.stdout == ""  # stdout went to /dev/null
    assert procs.close_inherited(str(tmp_path / "missing")) == []
